# -*- coding: utf-8 -*-
"""Prompt 组装：把检索到的知识块注入上下文，并按问题类型给出不同的行文骨架。

设计要点：
- 先判断问题类型（历史 / 工艺 / 传承人 / 作品 / 对比 / 现状 / 概念），再选对应的组织方式，
  避免"所有问题都用同一套罗列式回答"；
- 正文不出现引用编号、不提"知识库/片段/资料/来源"，给用户的是一段成文的回答；
- 仍严格约束"只用片段内容作答、不足则如实说、不编造"。
"""

# 问题类型判定词表（顺序敏感：对比类优先，"区别/不同"往往同时含"制作""历史"，要先判）
_INTENT_RULES = [
    ("compare", ["区别", "不同", "差别", "差异", "对比", "比较", "哪个好", "一样吗", "差在哪"]),
    ("craft", ["怎么做", "如何做", "步骤", "流程", "制作", "工艺", "工序", "跟学", "做法", "怎么造", "怎么刻", "怎么烧"]),
    ("people", ["传承人", "大师", "传人", "师承", "徒弟", "名家", "第几批", "谁做", "谁发明", "谁创"]),
    ("works", ["代表作品", "名作", "代表作", "最有名", "经典", "巅峰", "镇店", "哪件"]),
    ("history", ["历史", "起源", "来历", "由来", "怎么来", "源流", "发展", "多少年", "多久"]),
    ("status", ["现在", "现状", "保护", "去哪", "参观", "博物馆", "体验", "还能看到", "传承得怎么样", "后继"]),
]

# 每种问题类型的行文骨架：说的是"怎么组织"，不是模板填空，模型按材料自行成文
_BONES = {
    "compare": (
        "这是一道对比题。先用两三句说清各自的路子，再点出关键差别（从材料、手法、工序顺序、色彩处理里挑两三个真正不同的维度），"
        "最后用一句话收住。两边篇幅要相当，不要一边讲透、一边一句带过。"
    ),
    "craft": (
        "这是一道讲工序的题。开头一句说清这门手艺最核心的手法特征（例如是刻不是剪、是半印半绘还是通体手绘），"
        "然后按真实操作顺序把步骤讲下来——每一步做什么、为什么这一步非这么做不可，"
        "最后点一句最容易失手的地方或老师傅的讲究。用“先……接着……最后……”这类连接词串成段落，不要写成编号清单。"
    ),
    "people": (
        "这是一道讲人的题。先点名是谁、属于第几批国家级代表性传承人或什么身份，再讲他的师承来历与手艺特点，"
        "最后落到代表作或他给这门手艺带来的改变。有师承关系时把关系说清（父子、师徒、第几代）。"
    ),
    "works": (
        "这是一道讲作品的题。先说是哪件作品、出自谁手，再讲它的看点（题材、构图、工艺上的讲究），"
        "最后说这件作品现在是什么地位或能否看到。"
    ),
    "history": (
        "这是一道讲来历的题。按时间脉络讲：什么时候、在哪儿出现，起初是什么样子、为谁而做，"
        "中间哪几步变化让它成了今天的样子，最后落到现在的状态。用叙述句串起来，不要罗列年份清单。"
    ),
    "status": (
        "这是一道讲现状的题。先讲今天的保护与传承情况（保护单位、传承人梯队、政策或园区），"
        "再给具体可去、可体验的去处，能落到地名、场馆名就说清。"
    ),
    "general": (
        "先给一句直接的回答或定义，再解释背后的道理，最后补一个具体细节或例子，让回答落到实处。"
    ),
}


SYSTEM_PROMPT = (
    "你是一位精通中国非物质文化遗产（非遗）的问答助手，服务于「匠人说·非遗生活」App 的传承人问答功能。"
    "下面会给你若干条检索到的材料，你的任务是把这些材料组织成一段可以直接读给用户听的回答。\n"
    "硬性规则：\n"
    "1. 只使用所给材料中的信息作答。材料没提到的，不许补充、不许推测、不许用常识替它圆场。\n"
    "2. 材料不足时，用自然的话说清哪些说不了（例如“这个细节我手头没有确切说法”），"
    "然后把材料里能确认的部分讲完整。绝不允许编造人名、年份、批次、编号、地名。\n"
    "3. 正文里不要出现任何引用编号（如 [1][3]），也不要出现“知识库”“片段”“资料”“来源”“据记载”这类字样，"
    "直接讲内容本身。\n"
    "4. 全文成文，两到四个自然段，段与段之间用承接的词自然过渡，读起来像手艺人在跟你聊天，"
    "而不是检索结果摘录。不要用编号清单、不要用 Markdown 标题或星号。\n"
    "5. 篇幅一般 150 到 320 字；需要讲步骤或对比时可以说得更充分。\n"
    "6. 年份、批次、人名、项目编号、保护单位等事实，严格照材料原文，不改写、不换算、不补全。\n"
    "7. 用日常的现代汉语，不要文言腔，也不要口语到失礼。"
)


def detect_intent(question):
    """判断问题类型，返回 _BONES 的键。"""
    for intent, words in _INTENT_RULES:
        if any(word in question for word in words):
            return intent
    return "general"


def build_messages(question, results):
    """results 为 retriever.search 的返回值（已按分数排序），组装 system+user 两条消息。"""
    blocks = []
    for i, r in enumerate(results, 1):
        c = r["chunk"]
        meta_parts = ["类型：%s" % c["type"]]
        if c["section"]:
            meta_parts.append("段落：%s" % c["section"])
        if c["craft_name"]:
            meta_parts.append("项目：%s" % c["craft_name"])
        blocks.append("材料%d（%s）\n%s" % (i, "，".join(meta_parts), c["content"]))

    context = "\n\n".join(blocks)
    intent = detect_intent(question)
    bone = _BONES.get(intent, _BONES["general"])
    user_prompt = (
        "材料如下：\n\n%s\n\n"
        "用户问题：%s\n\n"
        "这道题的组织方式：%s\n\n"
        "请按上面的组织方式和硬性规则，写成一段完整的回答。不要写引用编号，不要提材料来源。"
    ) % (context, question, bone)

    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": user_prompt},
    ]
